using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace PlaygroundGenerator;

[Generator]
public class ExtensionParityGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classDeclarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => s is ClassDeclarationSyntax,
                transform: static (ctx, _) => (ClassDeclarationSyntax)ctx.Node)
            .Where(static c => c.Identifier.Text == "SampleExtensions");

        var compilationAndClasses = context.CompilationProvider.Combine(classDeclarations.Collect());

        context.RegisterSourceOutput(compilationAndClasses, static (spc, source) =>
        {
            var (compilation, classes) = source;
            var classSyntax = classes.FirstOrDefault();
            if (classSyntax == null) return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("namespace PlaygroundApp;");
            sb.AppendLine("public static class RoslynExtractedData");
            sb.AppendLine("{");
            sb.AppendLine("    public static List<ExtensionBlockInfo> GetBlocks()");
            sb.AppendLine("    {");
            sb.AppendLine("        return new List<ExtensionBlockInfo>");
            sb.AppendLine("        {");

            // Extract blocks from classSyntax
            var members = classSyntax.Members.ToList();
            int i = 0;
            while (i < members.Count)
            {
                var memberText = members[i].ToString().Trim();
                if (memberText.StartsWith("extension"))
                {
                    // Found an extension block
                    // Header text: e.g. "extension(ref Point pt)" or "extension<T>(List<T> list) where T : class" or "extension(string)"
                    string header = memberText.Split('{')[0].Trim();
                    
                    // Parse generic parameters on block
                    string genericParamsCode = "new List<GenericParamInfo>()";
                    if (header.Contains("<") && header.IndexOf("<") < header.IndexOf("("))
                    {
                        int openAngle = header.IndexOf("<");
                        int closeAngle = header.IndexOf(">");
                        string genName = header.Substring(openAngle + 1, closeAngle - openAngle - 1).Trim();
                        
                        string constraintCode = "new List<string>()";
                        if (header.Contains("where"))
                        {
                            string whereClause = header.Substring(header.IndexOf("where")).Trim();
                            var constraints = whereClause.Split(':').Last().Split(',').Select(c => $"\"{c.Trim()}\"");
                            constraintCode = $"new List<string> {{ {string.Join(", ", constraints)} }}";
                        }
                        genericParamsCode = $"new List<GenericParamInfo> {{ new GenericParamInfo(\"{genName}\", {constraintCode}) }}";
                    }

                    // Parse receiver
                    int openParen = header.IndexOf("(");
                    int closeParen = header.IndexOf(")");
                    string paramContent = header.Substring(openParen + 1, closeParen - openParen - 1).Trim();

                    bool isStatic = true;
                    string receiverCode = "null";
                    string extendedType = paramContent;

                    var paramParts = paramContent.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
                    if (paramParts.Length >= 2)
                    {
                        // Named receiver: e.g. "ref Point pt" or "List<T> list"
                        isStatic = false;
                        string paramName = paramParts.Last();
                        string modifiers = "none";
                        string typeName = "";

                        if (paramParts.Length == 3)
                        {
                            modifiers = paramParts[0]; // e.g. "ref", "in"
                            typeName = paramParts[1];
                        }
                        else
                        {
                            typeName = paramParts[0];
                        }

                        extendedType = typeName;
                        receiverCode = $"new ReceiverInfo(\"{paramName}\", \"{typeName}\", \"{modifiers}\")";
                    }

                    // Collect members inside this block
                    var memberCodes = new List<string>();
                    int j = i + 1;
                    while (j < members.Count && !members[j].ToString().Trim().StartsWith("extension"))
                    {
                        var m = members[j];
                        if (m is PropertyDeclarationSyntax prop)
                        {
                            bool isMemberStatic = prop.Modifiers.Any(SyntaxKind.StaticKeyword);
                            string propName = prop.Identifier.Text;
                            string retType = prop.Type.ToString();

                            memberCodes.Add($@"new ExtensionMemberInfo(
                                Kind: ""Property"",
                                Name: ""{propName}"",
                                IsStatic: {isMemberStatic.ToString().ToLower()},
                                ReturnType: ""{retType}"",
                                Accessors: new List<string> {{ ""get"" }},
                                Parameters: new List<MemberParamInfo>(),
                                GenericParameters: new List<GenericParamInfo>()
                            )");
                        }
                        else if (m is MethodDeclarationSyntax method)
                        {
                            bool isMemberStatic = method.Modifiers.Any(SyntaxKind.StaticKeyword);
                            string methodName = method.Identifier.Text;
                            string retType = method.ReturnType.ToString();

                            var paramListCodes = new List<string>();
                            foreach (var p in method.ParameterList.Parameters)
                            {
                                string pName = p.Identifier.Text;
                                string pType = p.Type?.ToString() ?? "";
                                string pMods = p.Modifiers.ToString();
                                if (string.IsNullOrEmpty(pMods)) pMods = "none";
                                paramListCodes.Add($"new MemberParamInfo(\"{pName}\", \"{pType}\", \"{pMods}\")");
                            }

                            memberCodes.Add($@"new ExtensionMemberInfo(
                                Kind: ""Method"",
                                Name: ""{methodName}"",
                                IsStatic: {isMemberStatic.ToString().ToLower()},
                                ReturnType: ""{retType}"",
                                Accessors: new List<string>(),
                                Parameters: new List<MemberParamInfo> {{ {string.Join(", ", paramListCodes)} }},
                                GenericParameters: new List<GenericParamInfo>()
                            )");
                        }
                        j++;
                    }

                    sb.AppendLine($@"            new ExtensionBlockInfo(
                IsStatic: {isStatic.ToString().ToLower()},
                Receiver: {receiverCode},
                ExtendedType: ""{extendedType}"",
                GenericParameters: {genericParamsCode},
                Members: new List<ExtensionMemberInfo>
                {{
                    {string.Join(",\n                    ", memberCodes)}
                }}
            ),");

                    i = j;
                }
                else
                {
                    i++;
                }
            }

            sb.AppendLine("        };");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            spc.AddSource("RoslynExtractedData.g.cs", sb.ToString());
        });
    }
}
