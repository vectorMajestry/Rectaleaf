using Reticleave.Metadata.TypeUsages.Interfaces;

namespace Reticleave.Metadata.Members.PropertyFamily.Properties;

/// <summary>
/// Represents a property in a type.
/// </summary>
/// <remarks>
/// This interface should not be implemented directly. 
/// Implement <see cref="IRefProperty{TKind, TMutability}"/>, <see cref="IStaticProperty{TKind, TAccess}"/>
/// or <see cref="IInstanceProperty{TKind, TAccess}"/> instead.
/// </remarks>
public interface IProperty<out TKind, out TAccess>
    where TAccess : IAccess
{
    string Name { get; }
    IHasProperties DeclaringType { get; }
    AccessModifier AccessModifier { get; }
    IInheritanceKind<IProperty<TKind, TAccess>> Inheritance { get; }
    IReadOnlyList<IAttribute> GetAttributes();

    /// <summary>
    /// An alternative way of querying for indexer accessors. Accessors queried this way are returned as
    /// <see cref="IAccessor{TKind}"/> where TKind is <see cref="IKnownOrNot"/>. Use extension properties
    /// from <see cref="IndexerExtensions"/> instead.
    /// </summary>
    [Obsolete]
    TAccess Accessors { get; }
}


/// <summary>
/// Represents a ref-returning property in a type.
/// </summary>.
/// <remarks>
/// This interface should not be implemented directly. 
/// Implement <see cref="IStaticRefProperty{TKind, TAccess}"/> or <see cref="IInstanceRefProperty{TKind, TAccess}"/> instead.
/// </remarks>
public interface IRefProperty<out TKind, out TMutability> : IProperty<TKind, IGet>
    where TKind : IKnownOrNot
    where TMutability : IMutOrNot
{
    IByRefType<TKind, TMutability> Type { get; }
}

/// <summary>
/// Represents a static ref-returning property in a type.
/// </summary>
public interface IStaticRefProperty<out TKind, out TMutability> : IRefProperty<TKind, TMutability>
    where TKind : IKnownOrNot
    where TMutability : IMutOrNot;


/// <summary>
/// Represents a instance (non-static) ref-returning property in a type.
/// </summary>
public interface IInstanceRefProperty<out TKind, out TMutability> : IRefProperty<TKind, TMutability>
    where TKind : IKnownOrNot
    where TMutability : IMutOrNot;

/// <summary>
/// Represents a regular property (not a ref-returning property) in a type.
/// </summary>.
/// <remarks>
/// This interface should not be implemented directly. 
/// Implement <see cref="IStaticProperty{TKind, TAccess}"/> or <see cref="IInstanceProperty{TKind, TAccess}"/> instead.
/// </remarks>
public interface IRegularProperty<out TKind, out TAccess> : IProperty<TKind, TAccess>
    where TKind : IKnownOrNot
    where TAccess : IAccess
{
    IComposableType<TKind> Type { get; }

    /// <summary>
    /// For automatically implemented properties, returns a backing field generated by the compiler. 
    /// The backing field cannot be discovered through <see cref="IHasFields.GetFields()"/>.
    /// </summary>
    IRegularField<TKind>? BackingField { get; }
}

/// <summary>
/// Represents a static property in a type.
/// </summary>
public interface IStaticProperty<out TKind, out TAccess> : IRegularProperty<TKind, TAccess>
    where TKind : IKnownOrNot
    where TAccess : IAccess;

/// <summary>
/// Represents an instance (non-static) property in a type.
/// </summary>
public interface IInstanceProperty<out TKind, out TAccess> : IRegularProperty<TKind, TAccess>
    where TKind : IKnownOrNot
    where TAccess : IAccess;

/// <summary>
/// Types of metadata objects that can be converted into a writable instance property metadata must implement this interface.
/// </summary>
internal interface IPropertyRequirement
{
    bool IsRequired { get; }
}

public static class PropertyExtensions
{
    extension<TKind>(IInstanceProperty<TKind, IWritable> writableInstanceProperty)
        where TKind : IKnownOrNot
    {
        public bool IsRequired => (writableInstanceProperty as IPropertyRequirement)?.IsRequired
            ?? throw new InvalidOperationException($"Property metadata type '{writableInstanceProperty.GetType().FullName}' does not implement '{nameof(IPropertyRequirement)}' interface. Types that can be cast to '{nameof(IInstanceProperty<,>)}' with a marker '{nameof(IWritable)}' must implement this interface.");
    }

    extension<TKind>(IRegularProperty<TKind, IAccess> property)
        where TKind : IKnownOrNot
    {
        public bool IsAutoProperty => property.BackingField is not null;
    }

#pragma warning disable CS0612

    extension<TKind>(IRefProperty<TKind, IMutOrNot> refProp)
        where TKind : IKnownOrNot
    {
        public IPropertyGetAccessor<TKind> Getter => (IPropertyGetAccessor<TKind>)refProp.Accessors.Getter;
    }

    extension<TKind>(IRegularProperty<TKind, IGet> property)
        where TKind : IKnownOrNot
    {
        public IPropertyGetAccessor<TKind> Getter => (IPropertyGetAccessor<TKind>)property.Accessors.Getter;
    }

    extension<TKind>(IRegularProperty<TKind, ISet> property)
        where TKind : IKnownOrNot
    {
        public IPropertySetAccessor<TKind> Setter => (IPropertySetAccessor<TKind>)property.Accessors.Setter;
    }

    extension<TKind>(IRegularProperty<TKind, IInit> property)
        where TKind : IKnownOrNot
    {
        public IPropertyInitAccessor<TKind> InitAccessor => (IPropertyInitAccessor<TKind>)property.Accessors.InitAccessor;
    }

#pragma warning restore CS0612
}
